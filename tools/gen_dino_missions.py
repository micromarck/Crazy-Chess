def tyrant_hunt():
    W, H = 50, 42
    L = Level(W, H)
    rng = random.Random(7202)
    station = (17, 14, 33, 26)
    ring = (11, 8, 39, 32)          # the clearing round the station (the Tyrant's beat)
    open_areas = [ring, (18, 34, 32, 41), (36, 2, 46, 9)]
    trails = [[(25, 40), (25, 32)], [(41, 6), (36, 11)], [(4, 20), (11, 20)], [(46, 24), (39, 24)]]
    jungle(L, rng, open_areas, trails)
    for area in open_areas:
        fringe(L, rng, area, 45)
    L.fill(station[0] - 1, station[1] - 1, station[2] + 1, station[3] + 1, ".")
    # The research station: an outer wall with 2-wide doorways (too narrow
    # for the Tyrant), a few rooms inside, wrecked in places.
    x0, y0, x1, y1 = station
    L.room(x0, y0, x1, y1, "H")
    for (dx, dy) in [((x0 + x1) // 2, y0), ((x0 + x1) // 2, y1)]:
        L.set(dx, dy, ".")
        L.set(dx + 1, dy, ".")
    for (dx, dy) in [(x0, (y0 + y1) // 2), (x1, (y0 + y1) // 2)]:
        L.set(dx, dy, ".")
        L.set(dx, dy + 1, ".")
    for y in range(y0 + 1, y1):           # inner walls with doorways
        if y not in (17, 18, 22, 23):
            L.set(21, y, "H")
            L.set(29, y, "H")
    for x in range(x0 + 1, 21):
        if x != 19:
            L.set(x, 20, "H")
    for x in range(30, x1):
        if x != 31:
            L.set(x, 20, "H")
    for (x, y) in [(23, 16), (27, 16), (24, 24), (26, 24), (19, 16), (31, 24)]:
        L.set(x, y, "h")                  # benches and consoles
    for (x, y) in [(x0 + 4, y0), (x1 - 4, y1), (x0, y1 - 2)]:
        L.set(x, y, "h")                  # wall breached to waist height
    L.prop("meds", "supply_medkit", 25, 22, cover="none")
    L.prop("ammo", "supply_ammo", 19, 23, cover="none")
    L.prop("ammo2", "supply_ammo", 31, 17, cover="none")
    # Fuel tanks round the clearing: bait.
    for i, (x, y) in enumerate([(13, 11), (37, 11), (13, 29), (37, 29)]):
        L.set(x, y, ".")
        L.prop(f"fuel{i}", "barrel", x, y, cover="half", hp=2,
               scripts='<script on="destroyed">message("A fuel tank goes up!"); explode(x, y, 2.5, 6); ignite(x, y, 2.5, 3);</script>')

    L.deploys.append(dict(team="player", squad="player", x=25, y=38))
    taken = set()
    # The Tyrant walks its beat round the station.
    tx, ty = spot(L, 13, 22, 3)
    beat = [(tx, ty), spot(L, 24, 11, 3), spot(L, 36, 22, 3), spot(L, 24, 31, 3)]
    taken |= footprint(tx, ty, 3)
    L.unit("enemy", "dino_tyrant", "The Tyrant", tx, ty, tag="tyrant", dormant=True, pod="tyrant", patrol=beat)
    # Raptors that followed it out: one pack in the north-east clearing, a
    # couple inside the station.
    for i, (x, y) in enumerate([(40, 5), (43, 7), (38, 8), (23, 18), (31, 22)]):
        x, y = spot(L, x, y, 1, taken)
        taken.add((x, y))
        L.unit("enemy", "dino_raptor", f"Raptor {i + 1}", x, y, dormant=True, pod="ne_pack" if i < 3 else "station")
    spawns = [(4, 20), (46, 24), (41, 2), (25, 41)]
    mx, my = spot(L, 41, 6, 3, taken)   # where the mate comes out (the north-east clearing)

    L.library = f"""
    // The mate comes out once (when the first is half dead, or dies).
    fn mate() {{
      if flag("mate") == 0 {{
        set_flag("mate", 1);
        spawn_unit("enemy", "dino_tyrant", "The Tyrant's Mate", {mx}, {my});
        message("An answering roar from the north-east. There are TWO of them!");
        objective("Kill both Tyrants");
      }}
    }}
    fn raptors(n) {{
      let pts = {rhai_points(spawns)};
      for i in 0..n {{
        let p = pts[rand(0, pts.len() - 1)];
        spawn_unit("enemy", "dino_raptor", "Raptor", p[0], p[1]);
      }}
    }}"""
    L.script("start", """
    set_flag("rage", 0); set_flag("mate", 0); set_flag("dead", 0);
    message("Something broke out of the research station three nights ago. It's still here.");
    message("The station's doorways are too narrow for it - but not for the raptors.");
    objective("Kill the Tyrant");""")
    L.script("turn_start", """
    let t = unit_by_tag("tyrant");
    if t >= 0 && unit_alive(t) && flag("rage") == 0 && unit_hp(t) <= unit_max_hp(t) / 2 {
      set_flag("rage", 1);
      message("The Tyrant bellows, and the jungle answers. Raptors are coming!");
      raptors(3);
      mate();
    }
    // Every few rounds a few more raptors come sniffing round.
    if round % 3 == 0 && alive_count("enemy") < 12 { raptors(2); }""", team="enemy")
    L.script("unit_killed", """
    if unit_class(unit) == "dino_tyrant" {
      set_flag("dead", flag("dead") + 1);
      if flag("dead") >= 2 {
        message("The second Tyrant crashes down. The jungle goes very quiet. Mission complete!");
        win();
      } else {
        message("The Tyrant crashes down...");
        mate();
      }
    }""")

    def look(x, y):
        if in_any(x, y, [(station[0], station[1], station[2], station[3])]):
            t = L.tiles[y][x]
            return "B" if t == "H" else ("c" if t == "." else None)
        return None

    finish(L, "tyrant_hunt",
           "  Tyrant Hunt: kill a Tyrant (3x3) that broke out of a jungle research\n"
           "  station (Dinosaurs module). The station's doorways are too narrow for it.",
           'id="tyrant_hunt" name="Tyrant Hunt" seed="65200" fog="true" win="script"',
           "A Tyrant broke out of a research station deep in the jungle and walks a beat around it. Kill it. The station's "
           "2-wide doorways are too narrow for it to follow you inside, but raptors are another matter, and wounding it "
           "calls more of them - and its mate. Fuel tanks around the clearing make good bait.",
           '<sky top="#2f5a3a" horizon="#cfd9a8"/>', surfaces(L, look))


