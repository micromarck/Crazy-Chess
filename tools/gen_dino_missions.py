# --- shared helpers ----------------------------------------------------------
def stamp_trails(trails, width=2):
    """Tiles within `width` of the polyline trails."""
    out = set()
    for path in trails:
        for (x0, y0), (x1, y1) in zip(path, path[1:]):
            n = max(abs(x1 - x0), abs(y1 - y0), 1) * 3
            for i in range(n + 1):
                cx = x0 + (x1 - x0) * i / n
                cy = y0 + (y1 - y0) * i / n
                for dx in range(-width, width + 1):
                    for dy in range(-width, width + 1):
                        out.add((round(cx) + dx, round(cy) + dy))
    return out


def in_any(x, y, areas):
    return any(x0 <= x <= x1 and y0 <= y <= y1 for x0, y0, x1, y1 in areas)


def jungle(L: Level, rng, open_areas, trails, trees=0.55, ferns=0.2):
    """Dense trees and ferns everywhere but the open areas and trails."""
    keep = stamp_trails(trails)
    for y in range(L.h):
        for x in range(L.w):
            if L.tiles[y][x] != "." or in_any(x, y, open_areas) or (x, y) in keep:
                continue
            r = rng.random()
            if r < trees:
                L.set(x, y, "H")
            elif r < trees + ferns:
                L.set(x, y, "h")


def fringe(L: Level, rng, area, per=40):
    """A few ferns along the edge of an open area (its middle stays clear for the big ones)."""
    x0, y0, x1, y1 = area
    for _ in range(max(1, (x1 - x0) * (y1 - y0) // per)):
        x, y = rng.randint(x0, x1), rng.randint(y0, y1)
        if x0 < x < x1 and y0 < y < y1:
            continue
        L.set(x, y, "h")


def spot(L: Level, x, y, side=1, taken=()):
    """Nearest place where a side x side unit fits."""
    for r in range(0, 10):
        for dy in range(-r, r + 1):
            for dx in range(-r, r + 1):
                cx, cy = x + dx, y + dy
                tiles = [(cx + i, cy - j) for i in range(side) for j in range(side)]
                if all(0 <= tx < L.w and 0 <= ty < L.h and L.tiles[ty][tx] == "."
                       and L.heights[ty][tx] == L.heights[cy][cx] and (tx, ty) not in taken for tx, ty in tiles):
                    return cx, cy
    raise SystemExit(f"no room for {side}x{side} near {x},{y}")


def footprint(x, y, side):
    return {(x + i, y - j) for i in range(side) for j in range(side)}


def surfaces(L: Level, special=lambda x, y: None) -> list[str]:
    rows = []
    for y in range(L.h):
        row = ""
        for x in range(L.w):
            t = L.tiles[y][x]
            s = special(x, y)
            if s:
                row += s
            elif t == "#":
                row += "W"
            elif t == "H":
                row += "R" if (x * 5 + y * 3) % 7 == 0 else "T"
            elif t == "h":
                row += "G"
            else:
                row += "d" if (x * 7 + y * 11) % 9 == 0 else "g"
        rows.append(row)
    return rows


def finish(L: Level, mid, header, attrs, description, sky, surf):
    L.check(mid)
    text = L.xml(header, attrs, description)
    text = text.replace("Generated by tools/gen_missions.py", "Generated by tools/gen_dino_missions.py")
    anchor = "  </heights>" if "  </heights>" in text else "  </layout>"
    text = text.replace(anchor, anchor + "\n  <surfaces>\n" + "\n".join("    " + r for r in surf) + "\n  </surfaces>", 1)
    text = text.replace("  <layout>", f"  {sky}\n\n  <layout>", 1)
    write(mid, text)


def rhai_points(pts):
    return "[" + ", ".join(f"[{x}, {y}]" for x, y in pts) + "]"


