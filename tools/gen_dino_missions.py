def nest_raid():
    W, H = 54, 36
    L = Level(W, H)
    rng = random.Random(7303)
    lz = (2, 26, 12, 34)
    nests = [(10, 6), (44, 8), (42, 28)]
    meadow = (20, 12, 34, 24)
    open_areas = [lz, meadow, (38, 0, 50, 6)] + [(x - 4, y - 3, x + 4, y + 3) for x, y in nests]
    trails = [[(7, 30), (14, 22), (10, 9)], [(12, 28), (24, 20), (32, 16), (42, 10)], [(14, 31), (30, 30), (40, 28)],
              [(27, 18), (40, 26)], [(10, 7), (24, 13)]]
    # A stream across the east side with a ford.
    for y in range(H):
        x = 36 + round(2 * __import__("math").sin(y / 4))
        if not (15 <= y <= 19):
            L.set(x, y, "#")
            L.set(x + 1, y, "#")
    jungle(L, rng, open_areas, trails, trees=0.5, ferns=0.25)
    for area in open_areas:
        fringe(L, rng, area, 25)
    L.fill(meadow[0] + 1, meadow[1] + 1, meadow[2] - 1, meadow[3] - 1, ".")
    for (x, y) in [(4, 27), (11, 33), (9, 28)]:
        L.set(x, y, "h")
    L.deploys.append(dict(team="player", squad="player", x=7, y=31))

    taken = set()
    eggs = []
    for i, (nx, ny) in enumerate(nests):
        # The nest: a ring of ferns, the egg in the middle.
        for dx, dy in [(-1, -1), (1, -1), (-1, 1), (1, 1)]:
            L.set(nx + dx, ny + dy, "h")
        L.set(nx, ny, ".")
        eggs.append((nx, ny))
        taken.add((nx, ny))
        for j, (dx, dy) in enumerate([(-3, 2), (3, -2), (2, 3)]):
            x, y = spot(L, nx + dx, ny + dy, 1, taken)
            taken.add((x, y))
            L.unit("enemy", "dino_raptor", f"Raptor {'ABC'[i]}{j + 1}", x, y, dormant=True, pod=f"nest{i}")
    # Two Hornbacks graze in the meadow.
    for i, (x, y) in enumerate([(24, 17), (30, 21)]):
        x, y = spot(L, x, y, 2, taken)
        taken |= footprint(x, y, 2)
        L.unit("enemy", "dino_hornback", f"Hornback {i + 1}", x, y, dormant=True, pod=f"meadow{i}",
               patrol=[(x, y), spot(L, x + 3, y - 3, 2), spot(L, x - 2, y + 2, 2)])
    tyrant_at = spot(L, 44, 4, 3)

    for i, (x, y) in enumerate(eggs):
        sx, sy = spot(L, x + 4, y, 1, taken)
        L.tile_script(x, y, f"""<script on="enter" team="player">
      if flag("egg{i}") == 0 {{
        set_flag("egg{i}", 1);
        set_flag("eggs", flag("eggs") + 1);
        zone_label("egg{i}", "NEST (empty)");
        message(unit_name(unit) + " grabs an egg. A furious shriek - the mother is coming!");
        spawn_unit("enemy", "dino_raptor", "Mother Raptor", {sx}, {sy});
        egg_taken();
      }}
    </script>""", marker="objective", label="RAPTOR NEST", tag=f"egg{i}")
    L.zone("lz", lz[0], lz[1], lz[2] - lz[0] + 1, lz[3] - lz[1] + 1, """<script on="enter" team="player">
      if flag("eggs") >= 3 {
        let squad = alive_count("player");
        let here = zone_count("lz", "player");
        if squad > 0 && here >= squad { message("Three eggs, everyone aboard. Mission complete!"); win(); }
        else { message(here + " of " + squad + " at the landing zone - everyone still alive has to make it."); }
      }
    </script>""", marker="evac", label="LANDING ZONE")
    L.library = f"""
    fn egg_taken() {{
      let n = flag("eggs");
      if n < 3 {{
        objective("Steal the raptor eggs: " + n + " of 3");
      }} else {{
        objective("Get the whole squad back to the landing zone");
        message("That's all three. Back to the landing zone!");
        if flag("tyrant") == 0 {{
          set_flag("tyrant", 1);
          spawn_unit("enemy", "dino_tyrant", "Tyrant", {tyrant_at[0]}, {tyrant_at[1]});
          message("Trees crack in the north-east. The eggs weren't only the raptors'...");
        }}
      }}
    }}"""
    L.script("start", """
    set_flag("eggs", 0); set_flag("tyrant", 0);
    message("Three raptor nests in this stretch of jungle. The lab wants an egg from each.");
    message("The packs sleep by their nests. Taking an egg brings its mother.");
    objective("Steal the raptor eggs: 0 of 3");""")
    L.script("turn_start", """
    let squad = alive_count("player");
    if flag("eggs") >= 3 && squad > 0 && zone_count("lz", "player") >= squad {
      message("Three eggs, everyone aboard. Mission complete!");
      win();
    }""", team="player")

    def look(x, y):
        if (x, y) in eggs:
            return "d"
        if in_any(x, y, [lz]) and L.tiles[y][x] == ".":
            return "c" if 4 <= x <= 9 and 29 <= y <= 33 else None
        return None

    finish(L, "nest_raid",
           "  Nest Raid: steal an egg from each of three raptor nests at night and get\n"
           "  back to the landing zone (Dinosaurs module).",
           'id="nest_raid" name="Nest Raid" seed="65300" fog="true" win="script"',
           "Night in the jungle. The lab wants an egg from each of three raptor nests. The packs sleep by their nests and "
           "every egg you take brings its mother screaming after you. Two Hornbacks graze in the meadow between them, a "
           "stream cuts off the east (one ford), and taking the third egg draws out something much bigger. Then get "
           "everyone back to the landing zone.",
           '<sky top="#0b1024" horizon="#2a3a5a"/>', surfaces(L, look))


def main():
    raptor_run()
    tyrant_hunt()
    nest_raid()


if __name__ == "__main__":
    main()
