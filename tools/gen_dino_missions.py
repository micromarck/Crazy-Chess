"""Generates the Dinosaurs module's extra missions:

    python3 tools/gen_dino_missions.py

* Raptor Run (raptor_run.mission.xml): a long dry canyon. Run it east to the
  evac before the chopper leaves (round 14) while raptor packs pour out of
  the side ravines and a Hornback herd grazes in the middle.
* Tyrant Hunt (tyrant_hunt.mission.xml): a Tyrant broke out of a jungle
  research station. Kill it (and its mate, who turns up once it's badly hurt). Its doorways are too narrow for the Tyrant but
  not for the raptors, and fuel tanks round the station make good bait.
* Nest Raid (nest_raid.mission.xml): at night, steal three eggs from three
  raptor nests and bring them back to the landing zone. Every egg wakes a
  mother; the third draws out the Tyrant.

(Lost Valley is tools/gen_dino.py.) Coordinates are mission coordinates:
x = column, y = row from the TOP. Big units (a Hornback is 2x2, the Tyrant
3x3) are placed by the corner with the lowest x and the BOTTOM row.
"""

from __future__ import annotations

