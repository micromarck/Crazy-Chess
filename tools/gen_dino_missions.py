def raptor_run():
    W, H = 64, 24
    L = Level(W, H)
    rng = random.Random(7101)
    mouths = [14, 26, 38, 50]   # ravines into the canyon, north and south
    # Canyon walls: rock along the top and bottom, ragged on the inside.
    for x in range(W):
        top = 2 + (rng.random() < 0.4)
        bottom = H - 3 - (rng.random() < 0.4)
        for y in range(H):
            if y < top or y > bottom:
                L.set(x, y, "H")
    for mx in mouths:
        for x in range(mx - 1, mx + 2):
            for y in list(range(0, 4)) + list(range(H - 4, H)):
                L.set(x, y, ".")
    # The dry riverbed: boulders and scrub (not too thick: a run, not a maze).
    for y in range(3, H - 3):
        for x in range(W):
            if L.tiles[y][x] != "." or x < 7 or x > W - 7:
                continue
            r = rng.random()
            if r < 0.07:
                L.set(x, y, "H")
            elif r < 0.17:
                L.set(x, y, "h")
    # The herd's flats in the middle stay open.
    flats = (28, 7, 40, 16)
    L.fill(flats[0], flats[1], flats[2], flats[3], ".")
    fringe(L, rng, flats, 30)
    # Rock shelves to shoot from (1 level up, reachable by a step).
    for x0, y0, x1, y1 in [(9, 4, 13, 6), (20, 16, 24, 19), (43, 4, 47, 6), (53, 16, 57, 19)]:
        L.raise_area(x0, y0, x1, y1, 1)
        L.fill(x0, y0, x1, y1, ".")
        L.set(x0 + 2, y0 if y0 > 10 else y1, "h")
    # Start and evac: clear.
    L.fill(1, 8, 6, 15, ".")
    L.fill(W - 6, 8, W - 2, 15, ".")
    L.deploys.append(dict(team="player", squad="player", x=3, y=12))

    taken = set()
    # The pack already on your trail (asleep in the first ravine until it hears you).
    for i, (x, y) in enumerate([(13, 2), (15, 2), (14, 21), (15, 22)]):
        x, y = spot(L, x, y, 1, taken)
        taken.add((x, y))
        L.unit("enemy", "dino_raptor", f"Raptor {i + 1}", x, y, dormant=True, pod="first_pack")
    # The Hornback herd on the flats.
    for i, (x, y) in enumerate([(31, 10), (36, 14)]):
        x, y = spot(L, x, y, 2, taken)
        taken |= footprint(x, y, 2)
        a = spot(L, x - 2, y - 2, 2)
        b = spot(L, x + 2, y + 1, 2)
        L.unit("enemy", "dino_hornback", f"Hornback {i + 1}", x, y, dormant=True, pod=f"herd{i}", patrol=[(x, y), a, b])

    spawns = [(mx, 0) for mx in mouths] + [(mx, H - 1) for mx in mouths]
    L.zone("evac", W - 6, 8, 5, 8, """<script on="enter" team="player">
      let squad = alive_count("player");
      let here = zone_count("evac", "player");
      if squad > 0 && here >= squad { message("Everyone's aboard - the chopper climbs out of the canyon. Mission complete!"); win(); }
      else { message(here + " of " + squad + " at the evac - the chopper won't leave anyone."); }
    </script>""", marker="evac", label="EVAC")
    L.library = f"""
    // Raptors pour out of the side ravines, most of all near the squad.
    fn pack_arrives() {{
      if round < 2 {{ return; }}
      let alive = alive_count("enemy");
      let n = rand(1, 3);
      if n > 14 - alive {{ n = 14 - alive; }}
      let pts = {rhai_points(spawns)};
      for i in 0..n {{
        let p = pts[rand(0, pts.len() - 1)];
        spawn_unit("enemy", "dino_raptor", "Raptor", p[0], p[1]);
      }}
      if n > 0 && flag("warned") == 0 {{
        set_flag("warned", 1);
        message("Shrieks echo down the ravines. More of them are coming.");
      }}
    }}"""
    L.script("start", """
    set_flag("warned", 0);
    message("The chopper can't land in the canyon - it'll wait at the far (east) end until round 14.");
    message("Raptors nest in the side ravines. Keep moving.");
    objective("Get the whole squad to the evac at the east end (round 14)");""")
    L.script("turn_start", "pack_arrives();", team="enemy")
    L.script("turn_start", """
    let left = 14 - round;
    let squad = alive_count("player");
    if squad > 0 && zone_count("evac", "player") >= squad {
      message("Everyone's aboard - the chopper climbs out of the canyon. Mission complete!");
      win();
    } else if left < 0 {
      message("The chopper couldn't wait any longer. It's gone.");
      lose();
    } else {
      objective("Get the whole squad to the evac at the east end: " + left + (if left == 1 { " turn left" } else { " turns left" }));
      if left <= 3 { message("The chopper leaves in " + left + (if left == 1 { " turn!" } else { " turns!" })); }
    }""", team="player")

    def look(x, y):
        if L.tiles[y][x] == "H":
            return "R"
        if L.tiles[y][x] == "." and L.heights[y][x] > 0:
            return "d"
        if L.tiles[y][x] == ".":
            return "d" if (x * 3 + y * 5) % 4 else "g"
        return None

    finish(L, "raptor_run",
           "  Raptor Run: run a dry canyon east to the evac (Dinosaurs module) while\n"
           "  raptors pour out of the side ravines; a Hornback herd grazes in the middle.",
           'id="raptor_run" name="Raptor Run" seed="65100" fog="true" win="script"',
           "The chopper can't set down in the canyon. Get the squad to the evac at its east end before it has to leave "
           "(round 14). Raptor packs keep spilling out of the side ravines, two Hornbacks graze on the flats in the middle "
           "(leave them be, or don't), and rock shelves give you somewhere to shoot from.",
           '<sky top="#6a8fbf" horizon="#f0c890"/>', surfaces(L, look))


