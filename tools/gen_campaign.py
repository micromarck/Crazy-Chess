def carve(L: Level, floors):
    """Floors from rectangles; walls ('H') round them; space ('#') beyond."""
    floor = {(x, y) for r in floors for x in range(r[0], r[2] + 1) for y in range(r[1], r[3] + 1)}
    for y in range(L.h):
        for x in range(L.w):
            if (x, y) in floor:
                L.set(x, y, ".")
                continue
            near = any((x + dx, y + dy) in floor for dx in (-1, 0, 1) for dy in (-1, 0, 1))
            L.set(x, y, "H" if near else "#")
    return floor


class Placer:
    def __init__(self, L: Level):
        self.L = L
        self.taken = set()

    def unit(self, cls, name, x, y, side=1, **kw):
        x, y = spot(self.L, x, y, side, self.taken)
        self.taken |= footprint(x, y, side)
        self.L.unit("enemy", cls, name, x, y, dormant=kw.pop("dormant", True), **kw)
        return x, y


def extract_script(zone, needs_flag, done_text, missing_text):
    return f"""<script on="enter" team="player">
      if flag("{needs_flag}") == 1 {{
        let squad = alive_count("player");
        let here = zone_count("{zone}", "player");
        if squad > 0 && here >= squad {{ message("{done_text}"); win(); }}
        else {{ message(here + " of " + squad + " here - everyone still alive has to make it."); }}
      }} else {{ message("{missing_text}"); }}
    </script>"""


def turn_check(zone, needs_flag, done_text):
    return f"""
    let squad = alive_count("player");
    if flag("{needs_flag}") == 1 && squad > 0 && zone_count("{zone}", "player") >= squad {{
      message("{done_text}");
      win();
    }}"""


def finish(L: Level, mid, name, seed, win, header, description, sky, surf):
    L.check(mid)
    text = L.xml(header, f'id="{mid}" name="{name}" seed="{seed}" fog="true" win="{win}"', description)
    text = text.replace("Generated by tools/gen_missions.py", "Generated by tools/gen_campaign.py")
    anchor = "  </heights>" if "  </heights>" in text else "  </layout>"
    rows = []
    for y in range(L.h):
        rows.append("".join(surf(x, y, L.tiles[y][x]) for x in range(L.w)))
    text = text.replace(anchor, anchor + "\n  <surfaces>\n" + "\n".join("    " + r for r in rows) + "\n  </surfaces>", 1)
    text = text.replace("  <layout>", f"  {sky}\n\n  <layout>", 1)
    write(mid, text)


