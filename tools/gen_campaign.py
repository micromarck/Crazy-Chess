# 7. The Heart
# =============================================================================
def heart():
    import math
    W, H = 40, 40
    L = Level(W, H)
    cx, cy = 20, 19
    floors = []
    for y in range(H):
        for x in range(W):
            if math.hypot(x - cx, y - cy) <= 17.5:
                floors.append((x, y, x, y))
    carve(L, floors)
    # Pillars in a ring; consoles round the plinth.
    for a in range(0, 360, 45):
        x = round(cx + 11 * math.cos(math.radians(a)))
        y = round(cy + 11 * math.sin(math.radians(a)))
        for dx in (0, 1):
            for dy in (0, 1):
                L.set(x + dx, y + dy, "H")
    for a in range(20, 360, 60):
        x = round(cx + 6 * math.cos(math.radians(a)))
        y = round(cy + 6 * math.sin(math.radians(a)))
        L.set(x, y, "h")
    L.deploys.append(dict(team="player", squad="player", x=20, y=35))
    P = Placer(L)
    P.unit("vesper_heart", "The Heart", 19, 20, side=2, tag="heart", pod="heart", dormant=False)
    P.unit("vesper_prime", "VESPER Prime", 20, 13, pod="heart")
    for i, (cls, x, y) in enumerate([
        ("fac_warden", 12, 14), ("fac_warden", 28, 24), ("fac_secbot", 26, 12), ("fac_secbot", 13, 25),
        ("fac_drone", 20, 8), ("fac_secbot", 30, 17), ("fac_secbot", 9, 19),
    ]):
        P.unit(cls, f"Guardian {i + 1}", x, y, pod="heart")
    L.prop("med", "supply_medkit", 16, 34, cover="none")
    L.prop("ammo", "supply_ammo", 24, 34, cover="none")
    L.script("start", """
    message("The Heart of VESPER: a sphere of light in a cage of cables, and everything it has left between you and it.");
    objective("Destroy the Heart");""")
    L.script("unit_killed", """
    if unit_class(unit) == "vesper_heart" {
      message("The Heart shrieks in a thousand synthesised voices and goes dark. Mission complete.");
      win();
    }""")
    finish(L, "camp_heart", "The Heart", 70707, "script",
           "  Ghost Protocol 7 - The Heart: destroy VESPER's Heart (a 2x2 machine that builds defenders).",
           "The Heart of VESPER, at the bottom of everything. It builds new defenders every few turns, VESPER Prime stands guard, and the Wardens with it. Destroy the Heart.",
           '<sky top="#020205" horizon="#20101a"/>',
           lambda x, y, t: "." if t == "#" else ("m" if t in "Hh" else ("c" if math.hypot(x - cx, y - cy) < 5 else "m")))


