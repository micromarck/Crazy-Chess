#!/usr/bin/env python3
"""Generates the Hold Out missions (assets/missions/holdout_*.mission.xml):

    python3 tools/gen_holdout.py

Survive as long as you can. There is no win: the waves never stop, and the
game remembers your best (the round you lasted to). Each enemy turn a wave
arrives at the edges of the map:

    rounds 1-3    1-3 enemies
    rounds 4-6    2-5
    rounds 7-11   4-7
    then every 5 rounds both ends x1.5, rounded up:
                  round 12: 6-11, round 17: 9-17, round 22: 14-26 ...

(At most a few dozen alive at once, so the game stays playable; the wave
waits for room.)

    holdout_square    Last Stand        zombies in a town square
    holdout_yard      Iron Tide         VESPER's robots in a facility yard
    holdout_hive      Feeding Frenzy    symbiotes in a station atrium

Coordinates are mission coordinates: x = column, y = row from the TOP.
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_missions import Level, write  # noqa: E402

W = H = 34

WAVE_LIB = """
    // The wave for round r: 1-3, then 2-5 from round 4, 4-7 from round 7,
    // then both ends x1.5 (rounded up) every 5 rounds.
    fn wave_size(r) {
      let lo = 1;
      let hi = 3;
      if r >= 4 { lo = 2; hi = 5; }
      if r >= 7 {
        lo = 4; hi = 7;
        let steps = (r - 7) / 5;
        for i in 0..steps {
          lo = (lo.to_float() * 1.5).ceiling().to_int();
          hi = (hi.to_float() * 1.5).ceiling().to_int();
        }
      }
      rand(lo, hi)
    }"""


def arena(cover_style: str) -> Level:
    """An open square with a defensible centre and scattered cover."""
    L = Level(W, H)
    c = W // 2
    # The centre: a ring of low cover with gaps, a pair of high blocks.
    for (x, y) in [(c - 3, c - 3), (c - 2, c - 3), (c + 2, c - 3), (c + 3, c - 3), (c - 3, c + 3), (c - 2, c + 3),
                   (c + 2, c + 3), (c + 3, c + 3), (c - 3, c - 1), (c - 3, c + 1), (c + 3, c - 1), (c + 3, c + 1)]:
        L.set(x, y, "h")
    for (x, y) in [(c - 1, c - 1), (c + 1, c + 1)]:
        L.set(x, y, "H")
    # Scattered cover further out (buildings / crates / pillars).
    blocks = [(6, 6), (25, 6), (6, 25), (25, 25), (16, 6), (16, 26), (6, 16), (26, 16)]
    for bx, by in blocks:
        for x in range(bx, bx + 3):
            for y in range(by, by + 2):
                L.set(x, y, "H")
    for (x, y) in [(10, 10), (23, 10), (10, 23), (23, 23), (12, 4), (21, 29), (4, 12), (29, 21), (13, 13), (20, 20), (20, 13), (13, 20)]:
        L.set(x, y, "h")
    return L


def edge_points():
    pts = []
    for i in range(2, W - 2, 3):
        pts += [(i, 0), (i, H - 1), (0, i), (W - 1, i)]
    return pts


def holdout(mid, name, seed, pick, cap, intro, description, sky, surf):
    L = arena("x")
    c = W // 2
    L.deploys.append(dict(team="player", squad="player", x=c, y=c))
    for tag, kind, x, y in [("med1", "supply_medkit", c - 2, c - 2), ("ammo1", "supply_ammo", c + 2, c + 2), ("ammo2", "supply_ammo", 8, 8),
                            ("med2", "supply_medkit", 26, 26), ("nade1", "supply_grenade", 26, 8), ("ammo3", "supply_ammo", 8, 26)]:
        L.set(x, y, ".")
        L.prop(tag, kind, x, y, cover="none")
    pts = "[" + ", ".join(f"[{x}, {y}]" for x, y in edge_points()) + "]"
    L.library = WAVE_LIB + f"""

    // Who comes: tougher enemies join as the rounds go on.
    fn pick_enemy(r) {{
{pick}
    }}

    fn spawn_wave() {{
      let n = wave_size(round);
      let room = {cap} - alive_count("enemy");
      if n > room {{ n = room; }}
      let pts = {pts};
      for i in 0..n {{
        let p = pts[rand(0, pts.len() - 1)];
        let e = pick_enemy(round);
        spawn_unit("enemy", e[0], e[1], p[0], p[1]);
      }}
      if n > 0 {{ message("Round " + round + ": " + n + " more coming."); }}
      ai_goal("enemy", {c}, {c});
    }}"""
    L.script("start", f"""
    message("{intro}");
    message("There's no winning here - hold out as long as you can. The waves grow every few rounds.");
    objective("Hold out: round 1");""")
    L.script("turn_start", "spawn_wave();", team="enemy")
    L.script("turn_start", """
    objective("Hold out: round " + round + " - next wave " + (if round < 4 { "1-3" } else if round < 7 { "2-5" } else { "bigger" }));""", team="player")
    L.check(mid)
    text = L.xml(
        f"  Hold Out - {name}: survive as long as you can against ever bigger waves.\n  Generated by tools/gen_holdout.py.",
        f'id="{mid}" name="Hold Out: {name}" seed="{seed}" fog="false" win="script"',
        description,
    )
    text = text.replace("Generated by tools/gen_missions.py", "Generated by tools/gen_holdout.py")
    rows = ["".join(surf(x, y, L.tiles[y][x]) for x in range(W)) for y in range(H)]
    text = text.replace("  </layout>", "  </layout>\n  <surfaces>\n" + "\n".join("    " + r for r in rows) + "\n  </surfaces>", 1)
    text = text.replace("  <layout>", f"  {sky}\n\n  <layout>", 1)
    write(mid, text)


